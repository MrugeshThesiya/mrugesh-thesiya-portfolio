/** Every glyph, keyed by the character it draws. */
export const FONT: ReadonlyMap<string, readonly number[]> = new Map(
  [...Object.entries(UPPER), ...Object.entries(LOWER), ...Object.entries(DIGITS), ...Object.entries(PUNCTUATION)].map(([character, rows]) => [
    character,
    glyph(...rows),
  ]),
)

/** The glyph for a character, or the blank one if it has none. */
export const glyphFor = (character: string): readonly number[] =>
  FONT.get(character) ?? FONT.get(' ')!

/** Every character the font can draw, sorted. */
export const CHARACTERS: readonly string[] = [...FONT.keys()].sort()

