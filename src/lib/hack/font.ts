/**
 * The font — eight rows of eight bits, one glyph per character.
 *
 * This file is the reason the screen map came first. A glyph here is not free
 * to be any shape: it has to be eight rows of eight bits, because `drawGlyph`
 * in screen.ts reads it that way and the whole machine is sixteen bits wide. Had
 * the font been designed first and fitted afterwards, every letter would have
 * been nudged and squashed to fit a grid that did not exist yet.
 *
 * Each glyph is written as five columns of pixels inside an eight-wide cell.
 * The right three columns and the bottom row stay clear: the right margin is what
 * separates one letter from the next, and the bottom row is what separates one
 * line of text from the next. Leaving them empty in the data rather than
 * adjusting at draw time means the spacing is part of the letter, which is where
 * it belongs.
 *
 * Rows are given as strings so they can be read as pictures. Bit 0 of a row is
 * the leftmost pixel, matching the rest of this project, so a row string is
 * reversed when it becomes a number.
 */

/**
 * Five pixels of glyph, seven rows, in an eight-by-eight cell.
 *
 * Seven rows is what a letter actually needs. The eighth row belongs to the
 * cell, not the letter: it is the gap under the baseline that keeps one line of
 * text from touching the next, so it is added here rather than drawn and left
 * to the caller to remember.
 */
const GLYPH_WIDTH = 5
const GLYPH_HEIGHT = 7

/** Rows in the machine's cell, which is one taller than a letter. */
const CELL_HEIGHT = 8

/** The rows, top to bottom, '#' meaning an inked pixel. */
type Sketch = readonly string[]

const glyph = (...rows: Sketch): readonly number[] => {
  if (rows.length !== GLYPH_HEIGHT) {
    throw new Error(`a glyph must be ${GLYPH_HEIGHT} rows, got ${rows.length}`)
  }

  const packed = rows.map((row) => {
    let bits = 0
    for (const [column, mark] of [...row].entries()) {
      if (mark === '#') bits |= 1 << column
    }
    return bits
  })

  // Pad to the cell height with a clear row.
  while (packed.length < CELL_HEIGHT) packed.push(0)
  return packed
}

